# pydantic allows for data validation
# this file will read from data/input and verify that everything is correct.

import os
from typing import TYPE_CHECKING, Literal, Any
from pydantic import BaseModel, TypeAdapter
from src import Log

if TYPE_CHECKING:  # type hints only: LLM_constrained imports this file
    from src.LLM_constrained import LLM_constrained


class TypeSpec(BaseModel):
    """Describe the different types allowed"""
    type: Literal["number", "string", "boolean", "integer"]

    def convert(self, text: str) -> float | int | bool | str:
        """
        turns the text generated by the llm into a python value, so that
        dump_json writes it with the right json type

        eg: number '2' -> 2.0, integer '4' -> 4, boolean 'true' -> True
        """
        match self.type:
            case "number":
                return float(text)
            case "integer":
                return int(text)
            case "boolean":
                return text == "true"
        return text


class FunctionDef(BaseModel):
    """Describe the functions allowed"""
    name: str
    description: str
    parameters: dict[str, TypeSpec]
    returns: TypeSpec

    def __str__(self) -> str:
        """
        eg:
        fn_add_numbers(a: number, b: number): Add two numbers together.
        """
        params: list[str] = []
        for key in self.parameters:
            params.append(key + ': ' + self.parameters[key].type)
        return f"{self.name}({', '.join(params)}): {self.description}"


class Prompt(BaseModel):
    """Describe a prompt"""
    prompt: str


class Answer(BaseModel):
    """Describe an answer"""
    prompt: str
    name: str = ""
    parameters: dict[str, Any] = {}


class Worker(BaseModel):
    """
    Models a worker, the jobs we have to do.
    Has the list of prompts and functions allowed.

    jobs.functions[0].name -> 'fn_add_numbers'
    jobs.functions[0].parameters['b'].type -> 'number'
    """
    jobs: list[Prompt]
    functions: list[FunctionDef]
    answers: list[Answer] = []

    def export_to_json(self, path: str) -> None:
        """
        When the jobs are done, we export the json
        """
        folder = os.path.dirname(path)
        if folder:  # if the path has a folder: make one
            os.makedirs(folder, exist_ok=True)
        with open(path, "wb") as f:
            f.write(
                TypeAdapter(
                    list[Answer]).dump_json(
                    self.answers,
                    indent=2))

    def get_fn_by_name(self, name: str) -> FunctionDef:
        """Get the function with name."""
        for fn in self.functions:
            if name == fn.name:
                return fn
        raise ValueError(f"{name} isnt any of the available functions")

    def solve(self, llm: "LLM_constrained", job: Prompt) -> Answer:
        """
        Answer a single Prompt: the model picks the function by its name,
        then fills its arguments

        Raises:
            ValueError: if the model can't produce a valid call
        """

        def build_name_prompt() -> str:
            """
            prompt to pick the function, the model only answers with its name
            """
            functions_desc = "\n".join(str(f) for f in self.functions)
            return (
                "<|im_start|>system\n"
                "You choose the correct function name, "
                "between quotation marks.\n"
                "Available functions:\n"
                f"{functions_desc}\n\n"
                '<|im_end|>\n'
                "<|im_start|>user\n"
                f"{job.prompt}<|im_end|>\n"
                "<|im_start|>assistant\n"
                "<think>\n\n</think>\n\n"
                '"'
            )

        def build_args_prompt(fn: FunctionDef) -> str:
            """
            prompt to fill the arguments of `fn`
            ends right before the answer, generate_object() writes the JSON
            """
            return (
                "<|im_start|>system\n"
                "You fill in the arguments of a function call.\n"
                f"Function: {fn}\n\n"
                "Answer with the arguments as JSON.<|im_end|>\n"
                "<|im_start|>user\n"
                f"{job.prompt}<|im_end|>\n"
                "<|im_start|>assistant\n"
                "<think>\n\n</think>\n\n"
            )

        prompt = build_name_prompt()
        Log.debug(prompt)

        Log.info(f"* * * {job.prompt} * * *")

        fn_name = llm.generate_from(
            prompt, options=[f.name for f in self.functions], end='"')
        Log.info(fn_name)

        chosen_fn = self.get_fn_by_name(fn_name)
        prompt = build_args_prompt(chosen_fn)
        Log.debug(prompt)

        parameters = llm.generate_object(prompt, chosen_fn.parameters)
        return Answer(prompt=job.prompt, name=fn_name, parameters=parameters)

    def run(self, llm: "LLM_constrained") -> None:
        """
        Solve every job. A failed one is logged and gets no answer
        """
        while self.jobs:
            job = self.jobs.pop(0)
            try:
                # only appended when nothing failed: no half-filled Answer
                self.answers.append(self.solve(llm, job))
            except ValueError as e:
                Log.error(f"this prompt failed: {job.prompt}")
                Log.error(f"reason: {e}")
